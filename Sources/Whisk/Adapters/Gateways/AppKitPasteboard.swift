import AppKit

/// Reads and writes the system pasteboard. Change detection relies on
/// `changeCount`; our own writes advance the counter and are skipped so a
/// selection is not re-captured.
final class AppKitPasteboard: Whisk.Pasteboard {
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    private let board: NSPasteboard
    private var lastChangeCount: Int
    private let didWrite: () -> Void
    private let readQueue: DispatchQueue
    private var lastKnownAccess: PasteboardAccess
    private let revisionLock = NSLock()
    private var readRevision: UInt64 = 0
    private var currentRevision: UInt64 { revisionLock.withLock { readRevision } }
    private func invalidateReads() { revisionLock.withLock { readRevision &+= 1 } }
    private var capturePaused = false
    private var failedReadCount = 0
    private var retryChangeCount: Int?

    init(
        board: NSPasteboard = .general, readQueue: DispatchQueue? = nil, didWrite: @escaping () -> Void = {}
    ) {
        self.board = board
        self.didWrite = didWrite
        self.readQueue = readQueue ?? DispatchQueue(label: "dev.whisky.maclx.pasteboard-read", qos: .utility)
        lastChangeCount = board.changeCount
        lastKnownAccess = Self.systemAccess(board)
    }

    /// The system's stance on reads that no paste of the user triggered.
    /// Systems without the notion let every read through.
    var access: PasteboardAccess { lastKnownAccess }

    private static func systemAccess(_ board: NSPasteboard) -> PasteboardAccess {
        if #available(macOS 15.4, *) {
            return Self.access(for: board.accessBehavior)
        }
        return .granted
    }

    @available(macOS 15.4, *)
    static func access(for behavior: NSPasteboard.AccessBehavior) -> PasteboardAccess {
        switch behavior {
        case .alwaysAllow: .granted
        case .alwaysDeny: .denied
        case .default, .ask: .requiresConsent
        @unknown default: .requiresConsent
        }
    }

    /// One read on purpose. Where the system asks before a read, this is
    /// the read that makes it ask, and the app is listed in System
    /// Settings from then on; elsewhere it is a no-op.
    func requestAccess() {
        invalidateReads()
        _ = board.string(forType: .string)
        lastKnownAccess = Self.systemAccess(board)
    }

    func setCapturePaused(_ paused: Bool) {
        guard capturePaused != paused else { return }
        capturePaused = paused
        invalidateReads()
        if !paused {
            // Sample at the resume action, not at a later worker tick: a copy
            // made immediately after resuming must still be captured.
            lastChangeCount = board.changeCount
            retryChangeCount = nil
            failedReadCount = 0
        }
    }

    /// A read the system would answer with an alert would stop the app
    /// in its tracks at every change, so the poll never makes one.
    func readIfChanged() -> PasteboardSnapshot? {
        invalidateReads()
        lastKnownAccess = Self.systemAccess(board)
        guard !capturePaused, lastKnownAccess == .granted else { return nil }
        let count = board.changeCount
        guard count != lastChangeCount else { return nil }
        lastChangeCount = count
        return snapshot(for: count)
    }

    /// The worker can remain blocked in a Continuity read; the controller never
    /// starts another read until this one returns.
    func readIfChangedAsync(_ completion: @escaping (PasteboardSnapshot?) -> Void) {
        precondition(Thread.isMainThread)
        let revision = currentRevision
        let readContents = !capturePaused
        let previousCount = lastChangeCount
        // Even accessBehavior and changeCount cross into the pasteboard
        // service. A poll must not wait for that service on the UI thread.
        readQueue.async { [self] in
            let access = Self.systemAccess(board)
            let count = readContents && access == .granted ? board.changeCount : previousCount
            let changed = count != previousCount && currentRevision == revision
            let result = changed ? snapshot(for: count) : nil
            DispatchQueue.main.async { [self] in
                // Own writes and explicit synchronous reads supersede the
                // worker. Validate local state here; never call the service.
                guard currentRevision == revision else { completion(nil); return }
                lastKnownAccess = access
                guard access == .granted, count != lastChangeCount else {
                    completion(nil)
                    return
                }
                if retryChangeCount != count {
                    retryChangeCount = count
                    failedReadCount = 0
                }
                if result != nil {
                    lastChangeCount = count
                    failedReadCount = 0
                    retryChangeCount = nil
                } else {
                    failedReadCount += 1
                    if failedReadCount >= 3 {
                        lastChangeCount = count
                        failedReadCount = 0
                        retryChangeCount = nil
                    }
                }
                completion(result)
            }
        }
    }

    private func snapshot(for count: Int) -> PasteboardSnapshot? {
        guard let types = board.types,
            !types.contains(where: { Self.concealedTypes.contains($0.rawValue) }),
            let payload = readPayload(availableTypes: Set(types))
        else { return nil }
        let app = Self.sourceApplication()
        var rtf: Data?
        if case .text = payload, types.contains(.rtf) {
            rtf = board.data(forType: .rtf)
        }
        guard board.changeCount == count else { return nil }
        return PasteboardSnapshot(
            payload: payload,
            source: Self.source(types: types, appName: app?.localizedName, bundleID: app?.bundleIdentifier),
            rtf: rtf
        )
    }

    /// Public pasteboard metadata access, with an undocumented hint. Presence
    /// is not authenticated; absence does not prove a local copy or reveal a
    /// device/app identity. Never call Continuity's private frameworks.
    static func source(types: [NSPasteboard.PasteboardType], appName: String?, bundleID: String?) -> SourceApp? {
        if types.contains(NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")) {
            return SourceApp(name: nil, origin: .handoffMarker)
        }
        return SourceApp(name: appName, bundleID: bundleID)
    }

    func write(_ payload: Payload, rtf: Data?) {
        write(payload, rtf: rtf, notify: true)
    }

    func writeForPaste(_ payload: Payload, rtf: Data?) {
        write(payload, rtf: rtf, notify: false)
    }

    private func write(_ payload: Payload, rtf: Data?, notify: Bool) {
        if case .storedImage(let reference) = payload {
            guard let data = try? reference.read() else { return }
            write(.image(data), rtf: rtf, notify: notify)
            return
        }
        invalidateReads()
        board.clearContents()
        let succeeded: Bool
        switch payload {
        case .storedImage: return
        case .text(let value):
            succeeded = board.setString(value, forType: .string)
            if let rtf {
                board.setData(rtf, forType: .rtf)
            }
        case .link(let url):
            succeeded = board.setString(url.absoluteString, forType: .string)
        case .image(let data):
            succeeded = board.setData(data, forType: .png)
        case .fileReferences(let paths):
            succeeded = board.writeObjects(paths.map { NSURL(fileURLWithPath: $0) })
        }
        lastChangeCount = board.changeCount
        retryChangeCount = nil
        failedReadCount = 0
        if succeeded, notify { didWrite() }
    }

    /// Explicit export only. Mark again so cooperating clipboard managers do
    /// not persist a session entry; this is not a system-wide guarantee.
    func writeSensitive(_ payload: Payload, rtf: Data?) {
        write(payload, rtf: rtf, notify: false)
        board.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        board.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        lastChangeCount = board.changeCount
        retryChangeCount = nil
        failedReadCount = 0
    }

    private static func sourceApplication() -> NSRunningApplication? {
        attributedSource(
            frontmost: NSWorkspace.shared.frontmostApplication,
            menuBarOwner: NSWorkspace.shared.menuBarOwningApplication)
    }

    /// The application the user attributes the copy to. During a screenshot
    /// to the clipboard the frontmost "app" is loginwindow (the capture HUD
    /// runs under it) — an accessory agent, not what the user was looking
    /// at. When the frontmost application isn't a regular one, the menu bar
    /// owner is.
    static func attributedSource(
        frontmost: NSRunningApplication?, menuBarOwner: NSRunningApplication?
    ) -> NSRunningApplication? {
        if let frontmost, frontmost.activationPolicy == .regular {
            return frontmost
        }
        return menuBarOwner ?? frontmost
    }

    private func readPayload(availableTypes types: Set<NSPasteboard.PasteboardType>) -> Payload? {
        if types.contains(.fileURL),
            let urls = board.readObjects(
                forClasses: [NSURL.self],
                options: [.urlReadingFileURLsOnly: true]
            ) as? [URL], !urls.isEmpty
        {
            return .fileReferences(urls.map(\.path))
        }
        if let png = imageData(availableTypes: types) {
            return .image(png)
        }
        if types.contains(.string), let string = board.string(forType: .string), !string.isEmpty {
            if let url = webLink(in: string) {
                return .link(url)
            }
            return .text(string)
        }
        return nil
    }

    private func imageData(availableTypes types: Set<NSPasteboard.PasteboardType>) -> Data? {
        if types.contains(.png), let png = board.data(forType: .png) {
            return png
        }
        if types.contains(.tiff), let tiff = board.data(forType: .tiff),
            let bitmap = NSBitmapImageRep(data: tiff),
            let png = bitmap.representation(using: .png, properties: [:])
        {
            return png
        }
        return nil
    }

    private func webLink(in string: String) -> URL? {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty,
            trimmed.rangeOfCharacter(from: .whitespacesAndNewlines) == nil,
            let url = URL(string: trimmed),
            let scheme = url.scheme?.lowercased(),
            scheme == "http" || scheme == "https"
        else { return nil }
        return url
    }
}
